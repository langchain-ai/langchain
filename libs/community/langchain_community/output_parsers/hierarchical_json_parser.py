"""
Hierarchical Robust JSON Output Parser for LangChain
Extracts, repairs, and parses nested JSON generated by LLMs with optional Pydantic schema validation.
"""

from __future__ import annotations

import json
import re
from typing import Any, Dict, Generic, List, Optional, Type, TypeVar, Union

T = TypeVar("T")


class OutputParserException(ValueError):
    """Exception raised when an LLM generation cannot be parsed into structured format."""
    pass


class HierarchicalRobustJsonParser(Generic[T]):
    """
    Robust output parser that extracts and repairs hierarchical JSON from LLM text generations.
    
    Handles:
    - Markdown fenced code blocks (```json ... ```, ``` ... ```)
    - Single quotes instead of double quotes
    - Trailing commas before closing braces/brackets
    - Missing closing brackets / braces in streaming or partial responses
    - Unquoted keys
    - Optional Pydantic model schema validation
    """

    def __init__(
        self,
        pydantic_object: Optional[Type[T]] = None,
        strict_validation: bool = False,
    ) -> None:
        self.pydantic_object = pydantic_object
        self.strict_validation = strict_validation

    @property
    def _type(self) -> str:
        return "hierarchical_robust_json_parser"

    def _extract_json_substring(self, text: str) -> str:
        """Extracts JSON substring from markdown code blocks or surrounding text."""
        code_block_match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", text, re.IGNORECASE)
        if code_block_match:
            return code_block_match.group(1).strip()

        json_match = re.search(r"(\{[\s\S]*\}|\[[\s\S]*\])", text)
        if json_match:
            return json_match.group(1).strip()

        return text.strip()

    def _repair_json_string(self, json_str: str) -> str:
        """Applies sanitization heuristics to fix common LLM formatting imperfections."""
        s = json_str.strip()
        s = re.sub(r"//.*$", "", s, flags=re.MULTILINE)
        s = re.sub(r"(?<=[{,:\s])'([^']+)'(?=[\s:,}\]])", r'"\1"', s)
        s = re.sub(r'([{,]\s*)([a-zA-Z_][a-zA-Z0-9_]*)(\s*:)', r'\1"\2"\3', s)
        s = re.sub(r",\s*([\]}])", r"\1", s)

        stack: list[str] = []
        in_string = False
        escape = False

        for char in s:
            if char == '"' and not escape:
                in_string = not in_string
            elif not in_string:
                if char in "{[":
                    stack.append("}" if char == "{" else "]")
                elif char in "}]":
                    if stack and stack[-1] == char:
                        stack.pop()
            escape = (char == "\\" and not escape)

        while stack:
            s += stack.pop()

        return s

    def parse(self, text: str) -> Union[Dict[str, Any], List[Any], T]:
        """Parses LLM generation text into a structured dictionary, list, or Pydantic instance."""
        raw_json_candidate = self._extract_json_substring(text)

        try:
            parsed = json.loads(raw_json_candidate)
            return self._validate(parsed)
        except json.JSONDecodeError:
            pass

        repaired_candidate = self._repair_json_string(raw_json_candidate)
        try:
            parsed = json.loads(repaired_candidate)
            return self._validate(parsed)
        except json.JSONDecodeError as err:
            raise OutputParserException(
                f"Failed to parse or repair JSON from LLM output: {text}. Error: {str(err)}"
            ) from err

    async def aparse(self, text: str) -> Union[Dict[str, Any], List[Any], T]:
        """Asynchronous parsing wrapper."""
        return self.parse(text)

    def _validate(self, parsed: Any) -> Union[Dict[str, Any], List[Any], T]:
        """Validates parsed JSON against Pydantic schema if provided."""
        if self.pydantic_object is not None:
            if isinstance(parsed, dict) and hasattr(self.pydantic_object, "model_validate"):
                try:
                    return self.pydantic_object.model_validate(parsed)
                except Exception as e:
                    if self.strict_validation:
                        raise OutputParserException(
                            f"Pydantic schema validation failed: {str(e)}"
                        ) from e
            elif isinstance(parsed, list) and not self.strict_validation:
                return parsed

        return parsed

    def get_format_instructions(self) -> str:
        """Returns instructions for prompting the LLM to output valid JSON."""
        if self.pydantic_object and hasattr(self.pydantic_object, "model_json_schema"):
            schema = json.dumps(self.pydantic_object.model_json_schema(), indent=2)
            return f"Return a valid JSON object matching the following schema:\n```json\n{schema}\n```"
        return "Return a valid JSON object or array."
